package planning.engine.planner.mpi.model.data.samples

import cats.syntax.all.*
import cats.syntax.ext.MT
import planning.engine.common.errors.*
import planning.engine.common.graph.edges.MeKey
import planning.engine.common.values.node.MnId
import planning.engine.common.values.sample.SampleId
import planning.engine.common.values.text.{Description, Name}
import planning.engine.planner.mpi.repr.{Representable, SampleRepr}
import planning.engine.planner.mpi.actors.node.Node

// Fully defined sample data, as they will read from map graph.
final case class Sample(
    id: SampleId,
    props: Sample.Props,
    info: Option[Sample.Info],
    edges: Set[MeKey],
    nodes: Map[MnId, Node],
) extends SampleRepr

object Sample:
  final case class Props(probabilityCount: Long, utility: Double)

  final case class Info(name: Name, description: Option[Description])

  sealed trait New extends Representable:
    def props: Props
    def edges: Set[MeKey]

    def getInfo: Option[Info] = this match
      case m: Man => Some(m.info)
      case _: Gen => None

    lazy val mnIds: Set[MnId] = edges.flatMap(_.mnIds)

  // Manually defined sample data, in this format they will be loaded from
  // initial/seed map graph, by Python script.
  // Compared to Gen, have additional info field, which can be used map analysis and visualization.
  final case class Man(props: Props, info: Info, edges: Set[MeKey]) extends New

  // Sample data generated by loopback learning algorithm.
  final case class Gen(props: Props, edges: Set[MeKey]) extends New

  def apply[F[_]: MT](id: SampleId, raw: New, nodes: Set[Node]): F[Sample] =
    for
      nodeMap <- nodes.map(n => n.mnId -> n).toMap.pure
      _ <- nodeMap.keySet.assertContainsAllOf(raw.mnIds, s"Sample $id has edges with MnIds not found in given nodes")
    yield Sample(
      id = id,
      props = raw.props,
      info = raw.getInfo,
      edges = raw.edges,
      nodes = nodeMap,
    )
